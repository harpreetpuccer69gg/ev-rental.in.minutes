function updateCarousel(){
  const city=(document.getElementById('citySelect').value||'').toLowerCase();
  const yuvwaaCities=['pune'];
  const yuluCities=vendors.filter(v=>v.Vendor==='Yulu').map(v=>(v.City||'').toLowerCase());
  const bounceCities=vendors.filter(v=>v.Vendor==='Bounce').map(v=>(v.City||'').toLowerCase());
  const slides=document.querySelectorAll('.hero-slide');
  if(!city){
    [1,2,3].forEach(i=>{slides[i].style.opacity='1';slides[i].style.pointerEvents='auto';});
    return;
  }
  slides[1].style.opacity=yuvwaaCities.includes(city)?'1':'0';
  slides[1].style.pointerEvents=yuvwaaCities.includes(city)?'auto':'none';
  slides[2].style.opacity=yuluCities.includes(city)?'1':'0';
  slides[2].style.pointerEvents=yuluCities.includes(city)?'auto':'none';
  slides[3].style.opacity=bounceCities.includes(city)?'1':'0';
  slides[3].style.pointerEvents=bounceCities.includes(city)?'auto':'none';
  // Reset to slide 0 and rebuild visible list
  curSlide=0;
  window._activeSlides=[0];
  if(yuvwaaCities.includes(city))window._activeSlides.push(1);
  if(yuluCities.includes(city))window._activeSlides.push(2);
  if(bounceCities.includes(city))window._activeSlides.push(3);
  // sync dots — show only dots for active slides
  const dots=document.querySelectorAll('.hero-dot');
  dots.forEach((d,i)=>d.style.display=window._activeSlides.includes(i)?'block':'none');
  goSlideActive(0);
}

function goSlideActive(n){
  const active=window._activeSlides||[0,1,2,3];
  const total=active.length;
  curSlide=(n%total+total)%total;
  const el=document.getElementById('heroSlides');
  if(!el)return;
  el.style.transform='translateX(-'+active[curSlide]*100+'%)';
  document.querySelectorAll('.hero-dot').forEach((d,i)=>d.classList.toggle('active',i===curSlide));
}

function goSlide(n){
  goSlideActive(n);
}

function handleSwipe(){
  const diff=touchStartX-touchEndX;
  if(Math.abs(diff)>40){
    if(diff>0)goSlide(curSlide+1);
    else goSlide(curSlide-1);
  }
}

window.addEventListener('load',()=>{
  const el=document.getElementById('heroSlides');
  if(!el)return;
  curSlide=0;
  el.style.transform='translateX(0)';
  document.querySelectorAll('.hero-dot').forEach((d,i)=>d.classList.toggle('active',i===0));

  autoScrollInterval=setInterval(()=>{ if(!isTouching)goSlide(curSlide+1); },5000);

  // Attach touch to outer .hero div — fixes iOS Safari swipe interception
  const hero=document.querySelector('.hero');
  hero.addEventListener('touchstart',(e)=>{
    isTouching=true;
    touchStartX=e.changedTouches[0].screenX;
  },{passive:true});
  hero.addEventListener('touchend',(e)=>{
    touchEndX=e.changedTouches[0].screenX;
    handleSwipe();
    setTimeout(()=>{isTouching=false;},600);
  },{passive:true});
});

